type GlyphElementOut =
  | { kind: "path"; d: string; fill?: string }
  | { kind: "circle"; cx: number; cy: number; r: number; fill?: string }
  | { kind: "line"; x1: number; y1: number; x2: number; y2: number };

function fmtNum(n: number): string {
  const rounded = Math.round(n * 10000) / 10000;
  return String(Object.is(rounded, -0) ? 0 : rounded);
}

function convertElement(el: SvgElement, context: string, errors: string[]): GlyphElementOut | null {
  for (const name of el.attrs.keys()) {
    if (!GEOMETRY_ATTRS.has(name)) {
      errors.push(`${context}: <${el.tag}> carries non-geometry attribute "${name}" (glyphs take one renderer-chosen paint)`);
      return null;
    }
  }
  const num = (name: string, fallback?: number): number => {
    const raw = el.attrs.get(name);
    const value = raw === undefined ? fallback : Number(raw);
    if (value === undefined || !Number.isFinite(value)) {
      errors.push(`${context}: <${el.tag}> needs a numeric "${name}" (got ${JSON.stringify(raw)})`);
      return Number.NaN;
    }
    return value;
  };
  /** Fixed-precision number, as emitted (same rounding as path coordinates). */
  const fixed = (n: number) => Number(fmtNum(n));
  const p = (x: number, y: number) => `${fmtNum(x)} ${fmtNum(y)}`;
  const before = errors.length;
  let out: GlyphElementOut | null = null;

  switch (el.tag) {
    case "path": {
      const d = el.attrs.get("d");
      if (d) out = { kind: "path", d };
      else errors.push(`${context}: <path> missing "d"`);
      break;
    }
    case "circle":
      out = { kind: "circle", cx: fixed(num("cx", 0)), cy: fixed(num("cy", 0)), r: fixed(num("r")) };
      break;
    case "line":
      out = {
        kind: "line",
        x1: fixed(num("x1", 0)),
        y1: fixed(num("y1", 0)),
        x2: fixed(num("x2", 0)),
        y2: fixed(num("y2", 0)),
      };
      break;
    case "rect": {
      const [x, y, w, h] = [num("x", 0), num("y", 0), num("width"), num("height")];
      const rxRaw = el.attrs.has("rx") ? num("rx") : undefined;
      const ryRaw = el.attrs.has("ry") ? num("ry") : undefined;
      const rx = Math.min(rxRaw ?? ryRaw ?? 0, w / 2);
      const ry = Math.min(ryRaw ?? rxRaw ?? 0, h / 2);
      if (rx === 0 || ry === 0) {
        out = { kind: "path", d: `M ${p(x, y)} L ${p(x + w, y)} L ${p(x + w, y + h)} L ${p(x, y + h)} Z` };
      } else {
        const arc = (tx: number, ty: number) => `A ${fmtNum(rx)} ${fmtNum(ry)} 0 0 1 ${p(tx, ty)}`;
        out = {
          kind: "path",
          d: [
            `M ${p(x + rx, y)}`, `L ${p(x + w - rx, y)}`, arc(x + w, y + ry),
            `L ${p(x + w, y + h - ry)}`, arc(x + w - rx, y + h),
            `L ${p(x + rx, y + h)}`, arc(x, y + h - ry),
            `L ${p(x, y + ry)}`, arc(x + rx, y), "Z",
          ].join(" "),
        };
      }
      break;
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [num("cx", 0), num("cy", 0), num("rx"), num("ry")];
      const r = `${fmtNum(rx)} ${fmtNum(ry)}`;
      out = { kind: "path", d: `M ${p(cx - rx, cy)} A ${r} 0 1 0 ${p(cx + rx, cy)} A ${r} 0 1 0 ${p(cx - rx, cy)} Z` };
      break;
    }
    case "polyline":
    case "polygon": {
      const nums = (el.attrs.get("points") ?? "").trim().split(/[\s,]+/).filter(Boolean).map(Number);
      if (nums.length < 4 || nums.length % 2 !== 0 || nums.some((n) => !Number.isFinite(n))) {
        errors.push(`${context}: <${el.tag}> has unparseable points`);
        break;
      }
      const pts: string[] = [];
      for (let i = 0; i < nums.length; i += 2) pts.push(p(nums[i]!, nums[i + 1]!));
      out = { kind: "path", d: `M ${pts.join(" L ")}${el.tag === "polygon" ? " Z" : ""}` };
      break;
    }
  }
  return errors.length === before ? out : null;
}

type GlyphBlock = {
  id: string;
  comment: string;
  viewBoxSize: number;
  /** Brands only: the square viewBox that sets the mark in its optical box (brandViewBox). */
  viewBox?: readonly [number, number, number, number];
  elements: GlyphElementOut[];
};

/** One Tabler outline icon → glyph block (root paint checked, bounding box stripped). */
function tablerGlyph(entry: GlyphEntry, text: string, errors: string[]): GlyphBlock | null {
  const context = `tabler/${entry.source}.svg (glyph "${entry.id}")`;
  const svg = parseSvg(context, text, errors);
  if (!svg) return null;
  let ok = true;
  for (const [name, value] of Object.entries(TABLER_ROOT_PAINT)) {
    if (svg.rootAttrs.get(name) !== value) {
      errors.push(`${context}: root ${name}="${svg.rootAttrs.get(name)}" (outline glyphs need ${name}="${value}")`);
      ok = false;
    }
  }
  const elements: GlyphElementOut[] = [];
  for (const el of svg.elements) {
    if (el.attrs.get("stroke") === "none") {
      // The only unpainted child Tabler ships is the 24x24 bounding box.
      if (el.tag !== "path" || el.attrs.get("d") !== TABLER_BOUNDING_BOX_D) {
        errors.push(`${context}: unexpected unstroked <${el.tag}> (only the bounding-box path is stripped)`);
        ok = false;
      }
      continue;
    }
    const out = convertElement(el, context, errors);
    if (out) elements.push(out);
    else ok = false;
  }
  if (ok && elements.length === 0) {
    errors.push(`${context}: no drawable elements`);
    ok = false;
  }
  return ok ? { id: entry.id, comment: `tabler: ${entry.source}`, viewBoxSize: svg.viewBoxSize, elements } : null;
}

/** One Simple Icons logo → glyph block (exactly one filled path). */
function brandGlyph(entry: GlyphEntry, text: string, errors: string[]): GlyphBlock | null {
  const context = `simple-icons/${entry.source}.svg (glyph "${entry.id}")`;
  const svg = parseSvg(context, text, errors);
  if (!svg) return null;
  if (svg.viewBoxSize !== 24 || svg.elements.length !== 1 || svg.elements[0]!.tag !== "path" || !svg.title) {
    errors.push(`${context}: expected a titled 24x24 logo with exactly one <path>`);
    return null;
  }
  const out = convertElement(svg.elements[0]!, context, errors);
  const license = entry.license ? ` — logo license ${entry.license}` : "";
  return out
    ? {
        id: entry.id,
        comment: `simple-icons: ${entry.source} (${svg.title})${license}`,
        viewBoxSize: 24,
        viewBox: brandViewBox([out], entry.id),
        elements: [out],
      }
    : null;
}

/**
 * One full-color mark (brand-art/<art>.svg) → glyph block: any "0 0 W H"
 * viewBox, every shape painted with its own `fill` (#RRGGBB), which the glyph
 * keeps per element.
 */
function brandArtGlyph(entry: GlyphEntry, text: string, errors: string[]): GlyphBlock | null {
  const context = `brand-art/${entry.art}.svg (glyph "${entry.id}")`;
  const root = parseAttrs(text.match(/<svg\b([^>]*)>/)?.[1] ?? "");
  const vb = (root.get("viewBox") ?? "").trim().split(/[\s,]+/).map(Number);
  const title = text.match(/<title>([^<]*)<\/title>/)?.[1];
  if (vb.length !== 4 || vb.some((n) => !Number.isFinite(n)) || vb[0] !== 0 || vb[1] !== 0 || !title) {
    errors.push(`${context}: expected a titled logo with a "0 0 W H" viewBox`);
    return null;
  }
  const elements: GlyphElementOut[] = [];
  for (const m of text.matchAll(/<(path|circle|ellipse)\b([^>]*?)\/?>/g)) {
    const attrs = parseAttrs(m[2]!);
    const fill = attrs.get("fill");
    attrs.delete("fill");
    if (!fill || !/^#[0-9A-F]{6}$/.test(fill)) {
      errors.push(`${context}: every <${m[1]}> needs fill="#RRGGBB"`);
      return null;
    }
    const out = convertElement({ tag: m[1]!, attrs }, context, errors);
    if (!out || out.kind === "line") return null;
    elements.push({ ...out, fill });
  }
  const size = Math.max(vb[2]!, vb[3]!);
  return { id: entry.id, comment: `brand-art: ${entry.art} (${title})`, viewBoxSize: size, viewBox: brandViewBox(elements, entry.id), elements };
}

// ---------------------------------------------------------------------------
// Optical box: every brand mark reads at one visual size
// ---------------------------------------------------------------------------

/**
 * A brand mark's square viewBox, centered on the mark's ink bounds. Its side
 * gives every mark one optical area: the mark's geometric-mean extent
 * √(w·h) fills BRAND_OPTICAL_AREA of the side, so a wide wordmark (Go) or a
 * tall one (Figma) is not drawn smaller than a square mark, while its long
 * side never passes BRAND_MAX_EXTENT of the box.
 */
function brandViewBox(elements: readonly GlyphElementOut[], id: string): readonly [number, number, number, number] {
  const box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
  const add = (x: number, y: number) => {
    box.minX = Math.min(box.minX, x);
    box.minY = Math.min(box.minY, y);
    box.maxX = Math.max(box.maxX, x);
    box.maxY = Math.max(box.maxY, y);
  };
  for (const el of elements) {
    if (el.kind === "path") flattenPath(el.d, add);
    else if (el.kind === "circle") {
      add(el.cx - el.r, el.cy - el.r);
      add(el.cx + el.r, el.cy + el.r);
    }
  }
  const w = box.maxX - box.minX;
  const h = box.maxY - box.minY;
  const scale = BRAND_OPTICAL_SCALE[id] ?? 1;
  const side = Math.max(
    Math.max(Math.max(w, h) / BRAND_MAX_EXTENT, Math.sqrt(w * h) / BRAND_OPTICAL_AREA) / scale,
    Math.max(w, h) / BRAND_SCALED_MAX_EXTENT,
  );
  const fix = (n: number) => Number(fmtNum(n));
  return [fix((box.minX + box.maxX - side) / 2), fix((box.minY + box.maxY - side) / 2), fix(side), fix(side)];
}

/** Share of the viewBox side a brand mark's geometric-mean extent fills. */
const BRAND_OPTICAL_AREA = 0.78;
/** Most of the viewBox side a brand mark's long side takes. */
const BRAND_MAX_EXTENT = 0.92;
/** Most of the viewBox side a mark's long side takes after its BRAND_OPTICAL_SCALE: never past the box. */
const BRAND_SCALED_MAX_EXTENT = 1;

