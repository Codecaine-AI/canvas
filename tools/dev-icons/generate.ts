/** Write `bytes` to `path` only when they differ (no mtime churn). */
function writeIfChanged(path: string, bytes: string | Buffer): boolean {
  const next = typeof bytes === "string" ? Buffer.from(bytes, "utf8") : bytes;
  if (existsSync(path) && readFileSync(path).equals(next)) return false;
  writeFileSync(path, next);
  return true;
}

function tarballUrl(pin: PackagePin): string {
  return `https://registry.npmjs.org/${pin.npm}/-/${pin.npm.split("/").pop()}-${pin.version}.tgz`;
}

/** One verified package's vendored files, held in memory until every package verifies. */
type StagedPackage = { key: PackageKey; files: Map<string, Buffer> };

/**
 * Download one pinned tarball, verify its sha512, and extract the license
 * file plus every SVG the manifest names. Records problems and returns null
 * on any failure — nothing is written to vendor/ here.
 */
async function stagePackage(manifest: Manifest, key: PackageKey, errors: string[]): Promise<StagedPackage | null> {
  const pin = manifest.packages[key];
  const url = tarballUrl(pin);
  let tgz: Buffer;
  try {
    const response = await fetch(url);
    if (!response.ok) {
      errors.push(`${key}: GET ${url} → HTTP ${response.status}`);
      return null;
    }
    tgz = Buffer.from(await response.arrayBuffer());
  } catch (e) {
    errors.push(`${key}: GET ${url} failed: ${(e as Error).message}`);
    return null;
  }
  const integrity = `sha512-${createHash("sha512").update(tgz).digest("base64")}`;
  if (integrity !== pin.integrity) {
    errors.push(`${key}: ${pin.npm}@${pin.version} tarball integrity ${integrity} does not match the pinned ${pin.integrity}`);
    return null;
  }
  const work = mkdtempSync(join(tmpdir(), "dev-icons-"));
  try {
    const tgzPath = join(work, "package.tgz");
    writeFileSync(tgzPath, tgz);
    // Distinct members only: GNU tar rejects a member named twice.
    const vendored = [pin.licenseFile, ...distinctSources(entriesFor(manifest, key)).map((source) => `${pin.iconDir}/${source}.svg`)];
    const members = key === "simple-icons" ? [...vendored, SIMPLE_ICONS_DATA] : vendored;
    const tar = Bun.spawnSync(["tar", "-xzf", tgzPath, "-C", work, ...members.map((member) => `package/${member}`)]);
    if (tar.exitCode !== 0) {
      errors.push(`${key}: extracting from ${pin.npm}@${pin.version} failed (a source name may not exist in this version):\n${tar.stderr.toString().trim()}`);
      return null;
    }
    const files = new Map<string, Buffer>();
    for (const member of vendored) {
      files.set(member.split("/").pop()!, readFileSync(join(work, "package", member)));
    }
    if (key === "simple-icons") {
      const data = namedRecords(manifest, JSON.parse(readFileSync(join(work, "package", SIMPLE_ICONS_DATA), "utf8")), errors);
      if (data) files.set(VENDORED_DATA, Buffer.from(data, "utf8"));
    }
    return { key, files };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

/**
 * The manifest's slugs' records out of the package's data/simple-icons.json,
 * each record verbatim, in package order: what the offline run reads for a
 * logo's title, brand color, aliases and per-logo license. A slug the package
 * lacks, or a logo whose license ALLOWED_LOGO_LICENSES refuses, is an error.
 */
function namedRecords(manifest: Manifest, data: unknown, errors: string[]): string | null {
  if (!Array.isArray(data)) {
    errors.push(`simple-icons: ${SIMPLE_ICONS_DATA} is not an icon list`);
    return null;
  }
  const logos = logoEntries(manifest);
  const wanted = new Set(logos.map((entry) => entry.source));
  const records = (data as SimpleIconRecord[]).filter((record) => wanted.has(record.slug));
  const found = new Map(records.map((record) => [record.slug, record]));
  for (const entry of logos) {
    const record = found.get(entry.source);
    if (!record) errors.push(`simple-icons: "${entry.id}" — slug "${entry.source}" is missing from ${SIMPLE_ICONS_DATA}`);
    else checkLogoLicense(entry.id, record, errors);
  }
  return `${JSON.stringify(records, null, 2)}\n`;
}

/** Write a staged package into vendor/<package>/ (which --vendor owns), pruning files it no longer names. */
function commitPackage(staged: StagedPackage): void {
  const outDir = resolve(VENDOR_DIR, staged.key);
  mkdirSync(outDir, { recursive: true });
  for (const [name, bytes] of staged.files) writeIfChanged(resolve(outDir, name), bytes);
  for (const name of readdirSync(outDir)) {
    if (!staged.files.has(name)) rmSync(resolve(outDir, name));
  }
}

