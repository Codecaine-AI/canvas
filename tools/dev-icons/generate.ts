const TOOL_DIR = import.meta.dir;
const REPO_ROOT = resolve(TOOL_DIR, "..", "..");
const MANIFEST_PATH = resolve(TOOL_DIR, "manifest.json");
const VENDOR_DIR = resolve(TOOL_DIR, "vendor");
const VERSIONS_PATH = resolve(VENDOR_DIR, "VERSIONS.md");
/** Canvas-content output: glyph data co-locates with the icon object def. */
const GLYPH_OUT_DIR = resolve(REPO_ROOT, "packages", "canvas", "src", "objects", "shapes", "icon");
export const TABLER_OUT_PATH = resolve(GLYPH_OUT_DIR, "icon-glyph-data-tabler.generated.ts");
export const BRANDS_OUT_PATH = resolve(GLYPH_OUT_DIR, "icon-glyph-data-brands.generated.ts");

const GENERATED_HEADER =
  "// GENERATED by tools/dev-icons/generate.ts — do not edit; edit tools/dev-icons/manifest.json and re-run `bun tools/dev-icons/generate.ts`";

/** Tabler's invisible bounding-box path, stripped from every outline icon. */
const TABLER_BOUNDING_BOX_D = "M0 0h24v24H0z";

/**
 * The uniform outline paint every Tabler icon must declare on its root. The
 * registry strokes all generic glyphs with one renderer-chosen width, so an
 * icon that deviates (a filled dot, a custom width) is rejected, not drawn wrong.
 */
const TABLER_ROOT_PAINT: Record<string, string> = {
  viewBox: "0 0 24 24",
  fill: "none",
  stroke: "currentColor",
  "stroke-width": "2",
  "stroke-linecap": "round",
  "stroke-linejoin": "round",
};

// ---------------------------------------------------------------------------
// Manifest
// ---------------------------------------------------------------------------

const PACKAGE_KEYS = ["tabler", "simple-icons"] as const;
type PackageKey = (typeof PACKAGE_KEYS)[number];

type PackagePin = {
  npm: string;
  version: string;
  integrity: string;
  license: string;
  /** License file at the package root, vendored beside the SVGs. */
  licenseFile: string;
  /** Directory (package-relative) holding `<source>.svg`. */
  iconDir: string;
};
type GlyphEntry = {
  id: string;
  source: string;
  /** Brands only: the SPDX id of a per-logo license Simple Icons records (absent = the package's CC0). */
  license?: string;
};
type Manifest = { packages: Record<PackageKey, PackagePin>; tabler: GlyphEntry[]; brands: GlyphEntry[] };

const BRAND_PREFIX = "brand-";

/** Simple Icons' icon metadata (package-relative) — read by --vendor to verify per-logo licenses, never vendored. */
const SIMPLE_ICONS_DATA = "data/simple-icons.json";

/** Load + validate the manifest; null (after recording problems) if unusable. */
function loadManifest(errors: string[]): Manifest | null {
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  } catch (e) {
    errors.push(`manifest ${MANIFEST_PATH}: ${(e as Error).message}`);
    return null;
  }
  const manifest = raw as Manifest;
  for (const key of PACKAGE_KEYS) {
    const pin = manifest.packages?.[key];
    const fields = ["npm", "version", "integrity", "license", "licenseFile", "iconDir"] as const;
    if (!pin || fields.some((field) => typeof pin[field] !== "string" || pin[field].length === 0)) {
      errors.push(`manifest: packages.${key} must set ${fields.join(", ")}`);
    } else if (!pin.integrity.startsWith("sha512-")) {
      errors.push(`manifest: packages.${key}.integrity must be a sha512 dist.integrity`);
    }
  }
  const seen = new Set<string>();
  const checkList = (list: GlyphEntry[] | undefined, name: "tabler" | "brands") => {
    if (!Array.isArray(list)) {
      errors.push(`manifest: "${name}" must be an array of { id, source }`);
      return;
    }
    for (const entry of list) {
      if (typeof entry?.id !== "string" || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(entry.id)) {
        errors.push(`manifest ${name}: invalid id ${JSON.stringify(entry?.id)}`);
        continue;
      }
      if (seen.has(entry.id)) errors.push(`manifest: duplicate glyph id "${entry.id}"`);
      seen.add(entry.id);
      if ((name === "brands") !== entry.id.startsWith(BRAND_PREFIX)) {
        errors.push(`manifest ${name}: "${entry.id}" — brand ids (and only brand ids) start with "${BRAND_PREFIX}"`);
      }
      if (typeof entry.source !== "string" || !/^[a-z0-9_-]+$/.test(entry.source)) {
        errors.push(`manifest ${name}: "${entry.id}" has invalid source ${JSON.stringify(entry.source)}`);
      }
      if (entry.license !== undefined && (name !== "brands" || !/^[A-Za-z0-9.+-]+$/.test(entry.license))) {
        errors.push(`manifest ${name}: "${entry.id}" — "license" is an SPDX id, and only brand entries carry one`);
      }
    }
  };
  checkList(manifest.tabler, "tabler");
  checkList(manifest.brands, "brands");
  return errors.length === 0 ? manifest : null;
}

function entriesFor(manifest: Manifest, key: PackageKey): GlyphEntry[] {
  return key === "tabler" ? manifest.tabler : manifest.brands;
}

/** The distinct source names a package's entries draw from (two ids may share one SVG). */
function distinctSources(entries: GlyphEntry[]): string[] {
  return [...new Set(entries.map((entry) => entry.source))];
}

// ---------------------------------------------------------------------------
// SVG parsing (tokenizer — both corpora are flat and regular)
// ---------------------------------------------------------------------------

type SvgElement = { tag: string; attrs: Map<string, string> };
type ParsedSvg = {
  rootAttrs: Map<string, string>;
  viewBoxSize: number;
  title: string | null;
  elements: SvgElement[];
};

const SUPPORTED_CHILD_TAGS = new Set(["path", "rect", "line", "polyline", "polygon", "circle", "ellipse"]);
/** Pure geometry attributes — anything else on a child (paint, transform) is rejected. */
const GEOMETRY_ATTRS = new Set(["d", "x", "y", "width", "height", "rx", "ry", "cx", "cy", "r", "x1", "y1", "x2", "y2", "points"]);

function parseAttrs(raw: string): Map<string, string> {
  const attrs = new Map<string, string>();
  for (const m of raw.matchAll(/([\w:-]+)\s*=\s*"([^"]*)"/g)) attrs.set(m[1]!, m[2]!);
  return attrs;
}

function parseSvg(context: string, text: string, errors: string[]): ParsedSvg | null {
  const root = text.match(/<svg\b([^>]*)>/);
  if (!root) {
    errors.push(`${context}: no <svg> root element`);
    return null;
  }
  const rootAttrs = parseAttrs(root[1]!);
  const vb = (rootAttrs.get("viewBox") ?? "").trim().split(/[\s,]+/).map(Number);
  if (vb.length !== 4 || vb.some((n) => !Number.isFinite(n)) || vb[0] !== 0 || vb[1] !== 0 || vb[2] !== vb[3]) {
    errors.push(`${context}: viewBox must be a square "0 0 N N" (got "${rootAttrs.get("viewBox")}")`);
    return null;
  }
  const title = text.match(/<title>([^<]*)<\/title>/)?.[1] ?? null;
  const elements: SvgElement[] = [];
  let ok = true;
  for (const m of text.matchAll(/<([a-zA-Z][\w:-]*)\b([^>]*?)\/?>/g)) {
    const tag = m[1]!;
    if (tag === "svg" || tag === "title") continue;
    if (!SUPPORTED_CHILD_TAGS.has(tag)) {
      errors.push(`${context}: unsupported element <${tag}>`);
      ok = false;
      continue;
    }
    elements.push({ tag, attrs: parseAttrs(m[2]!) });
  }
  return ok ? { rootAttrs, viewBoxSize: vb[2]!, title, elements } : null;
}

