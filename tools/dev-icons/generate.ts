function emitElement(el: GlyphElementOut): string {
  switch (el.kind) {
    case "path":
      return `{ kind: "path", d: ${JSON.stringify(el.d)}${el.fill ? `, fill: ${JSON.stringify(el.fill)}` : ""} }`;
    case "circle":
      return `{ kind: "circle", cx: ${el.cx}, cy: ${el.cy}, r: ${el.r}${el.fill ? `, fill: ${JSON.stringify(el.fill)}` : ""} }`;
    case "line":
      return `{ kind: "line", x1: ${el.x1}, y1: ${el.y1}, x2: ${el.x2}, y2: ${el.y2} }`;
  }
}

function emitModule(exportName: string, provenance: string[], doc: string, blocks: GlyphBlock[]): string {
  const sorted = [...blocks].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return [
    GENERATED_HEADER,
    ...provenance.map((line) => `// ${line}`),
    "",
    "// Structural twin of IconGlyphElement in ./icon-glyphs.ts (kept local to",
    "// avoid an import cycle — the shapes must stay assignment-compatible).",
    "type IconGlyphElement =",
    '  | { kind: "path"; d: string; fill?: string }',
    '  | { kind: "circle"; cx: number; cy: number; r: number; fill?: string }',
    '  | { kind: "line"; x1: number; y1: number; x2: number; y2: number };',
    "",
    `/** ${doc} */`,
    `export const ${exportName}: Record<`,
    "  string,",
    "  { viewBoxSize: number; viewBox?: readonly [number, number, number, number]; elements: readonly IconGlyphElement[] }",
    "> = {",
    ...sorted.map((block) =>
      [
        `  // ${block.comment}`,
        `  ${JSON.stringify(block.id)}: {`,
        `    viewBoxSize: ${block.viewBoxSize},`,
        ...(block.viewBox ? [`    viewBox: [${block.viewBox.join(", ")}],`] : []),
        "    elements: [",
        ...block.elements.map((el) => `      ${emitElement(el)},`),
        "    ],",
        "  },",
      ].join("\n"),
    ),
    "};",
    "",
  ].join("\n");
}

const byId = <T extends { id: string }>(a: T, b: T) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);

/** One brand catalog row, as emitted: what find_icon searches and what a fallback draws. */
type CatalogRow = { id: string; title: string; aliases: string[]; hex?: string; glyph?: string };

/**
 * The search words for a row: the manifest's own aliases, then what Simple
 * Icons records (`aka`, `old` names, and the titles of its duplicate marks),
 * lower case, without the title itself, each once.
 */
function rowAliases(title: string, own: readonly string[] | undefined, record: SimpleIconRecord | undefined): string[] {
  const words = [
    ...(own ?? []),
    ...(record?.aliases?.aka ?? []),
    ...(record?.aliases?.old ?? []),
    ...(record?.aliases?.dup ?? []).map((dup) => dup.title),
  ].map((word) => word.trim().toLowerCase());
  return [...new Set(words)].filter((word) => word !== "" && word !== title.toLowerCase());
}

/** The brand catalog table and the logo color table appended to the brands module, sorted by id. */
function emitBrandCatalog(rows: readonly CatalogRow[]): string {
  const sorted = [...rows].sort(byId);
  return [
    "",
    "/** Brand color per logo id: the `hex` Simple Icons records for the logo. Fallback rows have none. */",
    "export const BRAND_ICON_COLORS: Record<string, string> = {",
    ...sorted.filter((row) => row.hex).map((row) => `  ${JSON.stringify(row.id)}: ${JSON.stringify(row.hex)},`),
    "};",
    "",
    "/**",
    " * The brand catalog, one row per `brand-*` id: the product's title and search aliases, and either",
    " * `hex` (a logo in BRAND_ICON_GLYPH_ELEMENTS) or `glyph` (no logo: the generic glyph it draws).",
    " */",
    "export const BRAND_ICON_CATALOG: Record<",
    "  string,",
    "  { title: string; aliases: readonly string[]; hex?: string; glyph?: string }",
    "> = {",
    ...sorted.map((row) => {
      const paint = row.glyph ? `glyph: ${JSON.stringify(row.glyph)}` : `hex: ${JSON.stringify(row.hex)}`;
      return `  ${JSON.stringify(row.id)}: { title: ${JSON.stringify(row.title)}, aliases: ${JSON.stringify(row.aliases)}, ${paint} },`;
    }),
    "};",
    "",
  ].join("\n");
}

