/**
 * Deterministic dev-icon codegen: Tabler outline glyphs + Simple Icons brand
 * logos for the canvas `icon` object's glyph registry.
 *
 * Reads tools/dev-icons/manifest.json and the byte-verbatim SVGs vendored under
 * tools/dev-icons/vendor/, and emits three serializable modules:
 *   1. icon-glyph-data-tabler.generated.ts — Tabler outline geometry for every
 *      generic glyph id (24-unit grid, stroke paint).
 *   2. icon-glyph-data-brands.generated.ts — the brand catalog: every
 *      `brand-*` id's title, search aliases and either its Simple Icons logo
 *      (24-unit grid, fill paint, brand color) or the generic glyph it falls
 *      back to when Simple Icons has no logo for the product.
 *   3. state/schema/brand-icons.generated.ts — the catalog's id list, which
 *      the document schema validates icon ids against.
 *
 * Adding a brand is one manifest line, `{ "source": "<simple-icons slug>" }`
 * (its id defaults to `brand-<slug>`), then a `--vendor` run. The title, brand
 * color, aliases and logo license come from the pinned package's own data.
 *
 * Run:
 *   bun tools/dev-icons/generate.ts           offline: vendored SVGs → modules
 *   bun tools/dev-icons/generate.ts --vendor  network: re-vendor, then generate
 *
 * Pinning: manifest `packages` pins each upstream npm package to an exact
 * version AND its registry `dist.integrity`. `--vendor` downloads exactly that
 * tarball, refuses it unless its sha512 matches the pin, and refuses any logo
 * whose per-logo license (Simple Icons' `license`, absent = the package's CC0)
 * is not in ALLOWED_LOGO_LICENSES. Only when every package verifies does it
 * copy the SVGs the manifest names (plus each package's license file and the
 * named slugs' records from data/simple-icons.json) into vendor/<package>/,
 * prune files no longer named, and rewrite vendor/VERSIONS.md. To bump a package: set its new version + integrity (from
 * https://registry.npmjs.org/<npm>/<version> → dist.integrity), run with
 * --vendor, review the regenerated diff.
 *
 * The offline run never touches the network or the vendored files and is
 * idempotent: ids sorted, numbers fixed-precision, no timestamps, files only
 * rewritten when their bytes change. Tabler's invisible 24x24 bounding-box
 * path (`stroke="none" d="M0 0h24v24H0z"`) is stripped; rect / ellipse /
 * polyline / polygon convert to path data so every glyph stays inside the
 * registry's path | circle | line element model. All validation problems are
 * collected and reported together (the CLI then exits non-zero).
 *
 * No dependencies beyond node/bun builtins (plus the system `tar` for
 * --vendor). Both corpora are machine-generated and flat, so SVGs are parsed
 * with a small tokenizer, as in tools/nucleo-icons/generate.ts.
 */

