/** The vendored Simple Icons records by slug, or null (after recording the problem) when the file is missing. */
function vendoredRecords(errors: string[]): Map<string, SimpleIconRecord> | null {
  const path = resolve(VENDOR_DIR, "simple-icons", VENDORED_DATA);
  if (!existsSync(path)) {
    errors.push(`simple-icons/${VENDORED_DATA} is not vendored — run \`bun tools/dev-icons/generate.ts --vendor\``);
    return null;
  }
  const records = JSON.parse(readFileSync(path, "utf8")) as SimpleIconRecord[];
  return new Map(records.map((record) => [record.slug, record]));
}

/**
 * Render every generated module from the manifest + vendored files. Pure apart
 * from reading files: throws one Error listing every validation problem.
 */
export function renderDevIconModules(): DevIconModules {
  const errors: string[] = [];
  const manifest = loadManifest(errors);
  const records = manifest ? vendoredRecords(errors) : null;
  if (!manifest || !records) throw new Error(`dev icons: ${errors.length} error(s):\n  - ${errors.join("\n  - ")}`);

  const logos = logoEntries(manifest).map((entry) => {
    const record = records.get(entry.source);
    if (!record) errors.push(`simple-icons: "${entry.id}" — slug "${entry.source}" is not in the vendored ${VENDORED_DATA}; run --vendor`);
    else checkLogoLicense(entry.id, record, errors);
    return { ...entry, license: record?.license?.type, record };
  });
  const build = (key: PackageKey, entries: readonly GlyphEntry[], toBlock: typeof tablerGlyph): GlyphBlock[] => {
    const blocks: GlyphBlock[] = [];
    for (const entry of entries) {
      if (entry.art) {
        const artPath = resolve(BRAND_ART_DIR, `${entry.art}.svg`);
        const block = existsSync(artPath) ? brandArtGlyph(entry, readFileSync(artPath, "utf8"), errors) : null;
        if (!existsSync(artPath)) errors.push(`brand-art/${entry.art}.svg (glyph "${entry.id}") is missing`);
        if (block) blocks.push(block);
        continue;
      }
      const path = resolve(VENDOR_DIR, key, `${entry.source}.svg`);
      if (!existsSync(path)) {
        errors.push(`${key}/${entry.source}.svg (glyph "${entry.id}") is not vendored — run \`bun tools/dev-icons/generate.ts --vendor\``);
        continue;
      }
      const block = toBlock(entry, readFileSync(path, "utf8"), errors);
      if (block) blocks.push(block);
    }
    return blocks;
  };
  const tablerBlocks = build("tabler", manifest.tabler, tablerGlyph);
  const brandBlocks = build("simple-icons", logos, brandGlyph);
  if (errors.length > 0) throw new Error(`dev icons: ${errors.length} error(s):\n  - ${errors.join("\n  - ")}`);

  const rows: CatalogRow[] = [
    ...logos.map((entry) => ({
      id: entry.id,
      title: entry.record!.title,
      aliases: rowAliases(entry.record!.title, entry.aliases, entry.record),
      hex: `#${entry.record!.hex.toUpperCase()}`,
    })),
    ...manifest.brands.filter(isFallback).map((entry) => ({
      id: entry.id,
      title: entry.title,
      aliases: rowAliases(entry.title, entry.aliases, undefined),
      glyph: entry.glyph,
    })),
  ];
  const tabler = manifest.packages.tabler;
  const brands = manifest.packages["simple-icons"];
  return {
    tabler: emitModule(
      "TABLER_ICON_GLYPH_ELEMENTS",
      [
        `Source: ${tabler.npm}@${tabler.version} ${tabler.iconDir} (${tabler.license}) — vendored in tools/dev-icons/vendor/tabler/;`,
        "attribution in tools/dev-icons/THIRD-PARTY-NOTICES.md.",
      ],
      "Tabler outline geometry per glyph id — 24-unit grid, stroke paint, bounding-box path stripped.",
      tablerBlocks,
    ),
    brands: emitModule(
      "BRAND_ICON_GLYPH_ELEMENTS",
      [
        `Source: ${brands.npm}@${brands.version} ${brands.iconDir} (${brands.license}, except entries that name their own logo license) —`,
        "vendored in tools/dev-icons/vendor/simple-icons/. Logos are trademarks of their respective owners; see",
        "tools/dev-icons/THIRD-PARTY-NOTICES.md.",
      ],
      "Brand logo geometry per logo id, fill paint: the Simple Icons logo (24-unit grid, one color), or a full-color brand-art mark whose shapes keep their own `fill`. `viewBox` sets every mark in one optical box.",
      brandBlocks,
    ) + emitBrandCatalog(rows),
    brandIds: emitBrandIds(rows),
  };
}

/** A logo whose per-logo license is outside ALLOWED_LOGO_LICENSES is refused: pick another product or a fallback row. */
function checkLogoLicense(id: string, record: SimpleIconRecord, errors: string[]): void {
  const license = record.license?.type;
  if (license !== undefined && !ALLOWED_LOGO_LICENSES.has(license)) {
    errors.push(`simple-icons: "${id}" — the ${record.title} logo is licensed ${license}, which is not in ALLOWED_LOGO_LICENSES; drop it or make it a fallback row`);
  }
}

