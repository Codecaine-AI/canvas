const PACKAGE_KEYS = ["tabler", "simple-icons"] as const;
type PackageKey = (typeof PACKAGE_KEYS)[number];

type PackagePin = {
  npm: string;
  version: string;
  integrity: string;
  license: string;
  /** License file at the package root, vendored beside the SVGs. */
  licenseFile: string;
  /** Directory (package-relative) holding `<source>.svg`. */
  iconDir: string;
};
type GlyphEntry = {
  id: string;
  source: string;
  /** Brands only: the full-color mark (LogoEntry.art). */
  art?: string;
  /** Brands only: the per-logo license Simple Icons records, read from the vendored data (absent = CC0). */
  license?: string;
};
/** A brand Simple Icons draws: its slug, and optionally a nicer id, a full-color mark and extra search aliases. */
type LogoEntry = {
  /** Default `brand-<source>`. */
  id?: string;
  source: string;
  /** A full-color mark in brand-art/<art>.svg drawn instead of the one-color Simple Icons logo. */
  art?: string;
  /** Search words beyond the title and the aliases Simple Icons records, lower case. */
  aliases?: string[];
};
/** A product Simple Icons has no logo for: it draws a generic glyph and keeps its own id, title and aliases. */
type FallbackEntry = {
  id: string;
  title: string;
  /** The generic (Tabler) glyph id it draws. */
  glyph: string;
  aliases?: string[];
  /** Why there is no logo: kept in the manifest for the next reader. */
  why: string;
};
type BrandEntry = LogoEntry | FallbackEntry;
type Manifest = { packages: Record<PackageKey, PackagePin>; tabler: GlyphEntry[]; brands: BrandEntry[] };

const BRAND_PREFIX = "brand-";

const isFallback = (entry: BrandEntry): entry is FallbackEntry => "glyph" in entry;
const brandId = (entry: BrandEntry): string =>
  isFallback(entry) ? entry.id : entry.id ?? `${BRAND_PREFIX}${entry.source}`;

/** The logo entries, each with its resolved id, as glyph entries. */
function logoEntries(manifest: Manifest): (GlyphEntry & LogoEntry)[] {
  return manifest.brands.filter((entry): entry is LogoEntry => !isFallback(entry))
    .map((entry) => ({ ...entry, id: brandId(entry) }));
}

