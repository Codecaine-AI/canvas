/**
 * Per-logo licenses a vendored logo may carry besides the package's CC0:
 * permissive and attribution-only (THIRD-PARTY-NOTICES.md and the generated
 * table in vendor/VERSIONS.md give the attribution). Non-commercial,
 * no-derivatives, copyleft-code and custom terms are refused.
 */
const ALLOWED_LOGO_LICENSES: ReadonlySet<string> = new Set([
  "CC0-1.0", "Unlicense", "MIT", "BSD-3-Clause", "Apache-2.0",
  "CC-BY-3.0", "CC-BY-4.0", "CC-BY-SA-2.5", "CC-BY-SA-3.0", "CC-BY-SA-4.0",
]);

/** Load + validate the manifest; null (after recording problems) if unusable. */
function loadManifest(errors: string[]): Manifest | null {
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  } catch (e) {
    errors.push(`manifest ${MANIFEST_PATH}: ${(e as Error).message}`);
    return null;
  }
  const manifest = raw as Manifest;
  for (const key of PACKAGE_KEYS) {
    const pin = manifest.packages?.[key];
    const fields = ["npm", "version", "integrity", "license", "licenseFile", "iconDir"] as const;
    if (!pin || fields.some((field) => typeof pin[field] !== "string" || pin[field].length === 0)) {
      errors.push(`manifest: packages.${key} must set ${fields.join(", ")}`);
    } else if (!pin.integrity.startsWith("sha512-")) {
      errors.push(`manifest: packages.${key}.integrity must be a sha512 dist.integrity`);
    }
  }
  if (!Array.isArray(manifest.tabler) || !Array.isArray(manifest.brands)) {
    errors.push(`manifest: "tabler" and "brands" must be arrays`);
    return null;
  }
  const seen = new Set<string>();
  const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;
  const SLUG = /^[a-z0-9_-]+$/;
  const claim = (list: string, id: unknown, brand: boolean) => {
    if (typeof id !== "string" || !ID.test(id)) {
      errors.push(`manifest ${list}: invalid id ${JSON.stringify(id)}`);
      return;
    }
    if (seen.has(id)) errors.push(`manifest: duplicate glyph id "${id}"`);
    seen.add(id);
    if (brand !== id.startsWith(BRAND_PREFIX)) {
      errors.push(`manifest ${list}: "${id}" — brand ids (and only brand ids) start with "${BRAND_PREFIX}"`);
    }
  };
  for (const entry of manifest.tabler) {
    claim("tabler", entry?.id, false);
    if (typeof entry?.source !== "string" || !SLUG.test(entry.source)) {
      errors.push(`manifest tabler: "${entry?.id}" has invalid source ${JSON.stringify(entry?.source)}`);
    }
  }
  const tablerIds = new Set(manifest.tabler.map((entry) => entry.id));
  const LOGO_KEYS = new Set(["id", "source", "art", "aliases"]);
  const FALLBACK_KEYS = new Set(["id", "title", "glyph", "aliases", "why"]);
  for (const entry of manifest.brands) {
    const fallback = isFallback(entry);
    const id = typeof entry?.source === "string" && !fallback ? brandId(entry) : (entry as Partial<FallbackEntry>)?.id;
    claim("brands", id, true);
    const extra = Object.keys(entry ?? {}).filter((key) => !(fallback ? FALLBACK_KEYS : LOGO_KEYS).has(key));
    if (extra.length > 0) errors.push(`manifest brands: "${id}" carries unknown keys ${extra.join(", ")}`);
    if (fallback) {
      if (typeof entry.title !== "string" || entry.title.trim() === "" || typeof entry.why !== "string" || entry.why.trim() === "") {
        errors.push(`manifest brands: fallback "${id}" needs a "title" and a "why"`);
      }
      if (!tablerIds.has(entry.glyph)) {
        errors.push(`manifest brands: fallback "${id}" — "glyph" must be a generic glyph id (got ${JSON.stringify(entry.glyph)})`);
      }
    } else {
      if (typeof entry.source !== "string" || !SLUG.test(entry.source)) {
        errors.push(`manifest brands: "${id}" has invalid source ${JSON.stringify(entry.source)}`);
      }
      if (entry.art !== undefined && (typeof entry.art !== "string" || !SLUG.test(entry.art))) {
        errors.push(`manifest brands: "${id}" — "art" names a brand-art/<art>.svg file`);
      }
    }
    if (entry.aliases !== undefined && (!Array.isArray(entry.aliases)
      || entry.aliases.some((alias) => typeof alias !== "string" || alias !== alias.trim().toLowerCase() || alias === ""))) {
      errors.push(`manifest brands: "${id}" — "aliases" is a list of lower-case search words`);
    }
  }
  return errors.length === 0 ? manifest : null;
}

function entriesFor(manifest: Manifest, key: PackageKey): GlyphEntry[] {
  return key === "tabler" ? manifest.tabler : logoEntries(manifest);
}

/** The distinct source names a package's entries draw from (two ids may share one SVG). */
function distinctSources(entries: GlyphEntry[]): string[] {
  return [...new Set(entries.map((entry) => entry.source))];
}

