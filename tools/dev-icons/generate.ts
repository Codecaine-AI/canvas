/** Write `bytes` to `path` only when they differ (no mtime churn). */
function writeIfChanged(path: string, bytes: string | Buffer): boolean {
  const next = typeof bytes === "string" ? Buffer.from(bytes, "utf8") : bytes;
  if (existsSync(path) && readFileSync(path).equals(next)) return false;
  writeFileSync(path, next);
  return true;
}

function tarballUrl(pin: PackagePin): string {
  return `https://registry.npmjs.org/${pin.npm}/-/${pin.npm.split("/").pop()}-${pin.version}.tgz`;
}

/** One verified package's vendored files, held in memory until every package verifies. */
type StagedPackage = { key: PackageKey; files: Map<string, Buffer> };

/**
 * Download one pinned tarball, verify its sha512, and extract the license
 * file plus every SVG the manifest names. Records problems and returns null
 * on any failure — nothing is written to vendor/ here.
 */
async function stagePackage(manifest: Manifest, key: PackageKey, errors: string[]): Promise<StagedPackage | null> {
  const pin = manifest.packages[key];
  const url = tarballUrl(pin);
  let tgz: Buffer;
  try {
    const response = await fetch(url);
    if (!response.ok) {
      errors.push(`${key}: GET ${url} → HTTP ${response.status}`);
      return null;
    }
    tgz = Buffer.from(await response.arrayBuffer());
  } catch (e) {
    errors.push(`${key}: GET ${url} failed: ${(e as Error).message}`);
    return null;
  }
  const integrity = `sha512-${createHash("sha512").update(tgz).digest("base64")}`;
  if (integrity !== pin.integrity) {
    errors.push(`${key}: ${pin.npm}@${pin.version} tarball integrity ${integrity} does not match the pinned ${pin.integrity}`);
    return null;
  }
  const work = mkdtempSync(join(tmpdir(), "dev-icons-"));
  try {
    const tgzPath = join(work, "package.tgz");
    writeFileSync(tgzPath, tgz);
    // Distinct members only: GNU tar rejects a member named twice.
    const vendored = [pin.licenseFile, ...distinctSources(entriesFor(manifest, key)).map((source) => `${pin.iconDir}/${source}.svg`)];
    const members = key === "simple-icons" ? [...vendored, SIMPLE_ICONS_DATA] : vendored;
    const tar = Bun.spawnSync(["tar", "-xzf", tgzPath, "-C", work, ...members.map((member) => `package/${member}`)]);
    if (tar.exitCode !== 0) {
      errors.push(`${key}: extracting from ${pin.npm}@${pin.version} failed (a source name may not exist in this version):\n${tar.stderr.toString().trim()}`);
      return null;
    }
    if (key === "simple-icons") {
      checkBrandLicenses(manifest, JSON.parse(readFileSync(join(work, "package", SIMPLE_ICONS_DATA), "utf8")), errors);
    }
    const files = new Map<string, Buffer>();
    for (const member of vendored) {
      files.set(member.split("/").pop()!, readFileSync(join(work, "package", member)));
    }
    return { key, files };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

/**
 * Each brand entry's `license` must match the per-logo license Simple Icons
 * records for its slug (none = the package's CC0), so a version bump cannot
 * silently change what THIRD-PARTY-NOTICES.md has to say.
 */
function checkBrandLicenses(manifest: Manifest, data: unknown, errors: string[]): void {
  if (!Array.isArray(data)) {
    errors.push(`simple-icons: ${SIMPLE_ICONS_DATA} is not an icon list`);
    return;
  }
  const bySlug = new Map((data as { slug?: string; license?: { type?: string } }[]).map((icon) => [icon.slug, icon]));
  for (const entry of manifest.brands) {
    const icon = bySlug.get(entry.source);
    if (!icon) {
      errors.push(`simple-icons: "${entry.id}" — slug "${entry.source}" is missing from ${SIMPLE_ICONS_DATA}`);
    } else if (icon.license?.type !== entry.license) {
      errors.push(
        `simple-icons: "${entry.id}" — Simple Icons records logo license ${icon.license?.type ?? "none (CC0)"} but manifest.json says ${entry.license ?? "none"}; update manifest.json and THIRD-PARTY-NOTICES.md`,
      );
    }
  }
}

/** Write a staged package into vendor/<package>/ (which --vendor owns), pruning files it no longer names. */
function commitPackage(staged: StagedPackage): void {
  const outDir = resolve(VENDOR_DIR, staged.key);
  mkdirSync(outDir, { recursive: true });
  for (const [name, bytes] of staged.files) writeIfChanged(resolve(outDir, name), bytes);
  for (const name of readdirSync(outDir)) {
    if (!staged.files.has(name)) rmSync(resolve(outDir, name));
  }
}

function versionsNote(manifest: Manifest): string {
  const rows = PACKAGE_KEYS.map((key) => {
    const pin = manifest.packages[key];
    const entries = entriesFor(manifest, key);
    return `| \`${key}/\` | \`${pin.npm}\` | ${pin.version} | ${pin.license} (\`${key}/${pin.licenseFile}\`) | ${distinctSources(entries).length} SVGs for ${entries.length} glyph ids, from \`${pin.iconDir}/\` |`;
  });
  return [
    "# Vendored icon sources",
    "",
    "Written by `bun tools/dev-icons/generate.ts --vendor` from `../manifest.json` — do not edit by hand.",
    "Each file is a byte-verbatim copy out of the pinned npm tarball below; only the SVGs the manifest",
    "names are vendored, plus each package's license file.",
    "",
    "| dir | npm package | version | license | vendored |",
    "|---|---|---|---|---|",
    ...rows,
    "",
    "Per-logo licenses that Simple Icons records are declared on the brand entries in `../manifest.json`",
    "and verified against the package's `data/simple-icons.json` on every `--vendor` run.",
    "",
    "Pinned tarballs (sha512 `dist.integrity`, verified on every `--vendor` run):",
    "",
    ...PACKAGE_KEYS.map((key) => `- ${tarballUrl(manifest.packages[key])}\n  \`${manifest.packages[key].integrity}\``),
    "",
  ].join("\n");
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main(): Promise<void> {
  const errors: string[] = [];
  if (process.argv.includes("--vendor")) {
    const manifest = loadManifest(errors);
    if (manifest) {
      const staged: StagedPackage[] = [];
      for (const key of PACKAGE_KEYS) {
        const pkg = await stagePackage(manifest, key, errors);
        if (pkg) staged.push(pkg);
      }
      // All or nothing: vendor/ only changes once every package verified.
      if (errors.length === 0) {
        for (const pkg of staged) commitPackage(pkg);
        writeIfChanged(VERSIONS_PATH, versionsNote(manifest));
      }
    }
    if (errors.length > 0) {
      console.error(`dev icons: ${errors.length} error(s):\n  - ${errors.join("\n  - ")}`);
      process.exit(1);
    }
    console.log(`dev icons: vendored pinned sources → ${VENDOR_DIR}`);
  }

  let modules: DevIconModules;
  try {
    modules = renderDevIconModules();
  } catch (e) {
    console.error((e as Error).message);
    process.exit(1);
  }
  for (const [path, text] of [[TABLER_OUT_PATH, modules.tabler], [BRANDS_OUT_PATH, modules.brands]] as const) {
    const changed = writeIfChanged(path, text);
    console.log(`dev icons: ${changed ? "wrote" : "unchanged"} ${path}`);
  }
}

if (import.meta.main) await main();
